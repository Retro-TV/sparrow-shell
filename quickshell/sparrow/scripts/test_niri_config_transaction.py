        candidate = (
            "// Generated by Sparrow Display settings; do not edit.\n"
            'output "Example Panel Example-1 SERIAL" {\n'
            '    mode "1920x1080@60.000"\n'
            "    scale 1\n"
            '    transform "normal"\n'
            "    position x=0 y=0\n"
            "}\n"
        )
        transaction = self.transaction()
