    def test_udev_device_grouping_deduplicates_touchpad_mouse_interface(self):
        properties = {
            "/dev/input/event0": "ID_PATH_TAG=platform-i8042-serio-0\nID_INPUT_KEYBOARD=1\n",
            "/dev/input/event1": "ID_PATH_TAG=pci-0000-input-touch\nID_INPUT_TOUCHPAD=1\n",
            "/dev/input/event2": "ID_PATH_TAG=pci-0000-input-touch\nID_INPUT_MOUSE=1\n",
            "/dev/input/event3": "ID_PATH_TAG=usb-0000-mouse\nID_INPUT_MOUSE=1\n",
            "/dev/input/event4": "ID_PATH_TAG=usb-wacom\nID_INPUT_TABLET=1\n",
        }

        def fake_runner(args, **kwargs):
            return subprocess.CompletedProcess(args, 0, properties[args[-1]], "")

        devices = INPUT_INFO.discover_devices([Path(path) for path in properties], runner=fake_runner)
        self.assertEqual(devices, {
            "keyboard": True, "touchpad": True, "mouse": True,
            "tablet": True, "touchscreen": False,
        })

    def run_niri(self, args, **kwargs):
        if args[1:4] == ["msg", "action", "load-config-file"]:
            self.reload_count += 1
            if self.fail_next_reload:
                self.fail_next_reload = False
                return subprocess.CompletedProcess(args, 1, "", "simulated reload failure")
            return subprocess.CompletedProcess(args, 0, "", "")
        return subprocess.run(args, **kwargs)

    def transaction(self, runner=None, scheduler=None):
        return TRANSACTION.ConfigTransaction(
            self.config_root / "config.kdl",
            self.state_root,
            command_runner=runner or self.runner,
            rollback_scheduler=scheduler or self.scheduled_tokens.append,
        )

    def validate_active_fixture(self) -> None:
        result = subprocess.run(
            ["niri", "validate", "-c", str(self.config_root / "config.kdl")],
            text=True,
            capture_output=True,
            check=False,
        )
        self.assertEqual(result.returncode, 0, result.stderr or result.stdout)

    def test_valid_candidate_commits_backs_up_and_reloads(self):
        candidate = harmless_fragment("#aabbcc")
        result = self.transaction().transact("generated-colors", candidate)
        self.assertEqual(result["status"], "success", result)
        self.assertTrue(result["changed"])
        self.assertEqual(self.target.read_text(encoding="utf-8"), candidate)
        self.assertEqual(self.reload_count, 1)
        backup = Path(result["backupPath"])
        self.assertEqual((backup / self.target.name).read_text(encoding="utf-8"), self.original)
        metadata = json.loads((backup / "manifest.json").read_text(encoding="utf-8"))
        self.assertEqual(metadata["fragmentId"], "generated-colors")
        self.assertEqual(metadata["previousSha256"], __import__("hashlib").sha256(self.original.encode()).hexdigest())
        self.validate_active_fixture()

    def test_user_appearance_fragment_is_restricted_and_transactional(self):
        candidate = (
            "// Generated by Sparrow Look; do not edit.\n"
            "layout {\n"
            "    gaps 8\n"
            "    struts {\n"
            "        left 8\n"
            "        right 8\n"
            "        top -8\n"
            "        bottom 8\n"
            "    }\n"
            "    border {\n"
            "        width 2\n"
            "    }\n"
            "    shadow {\n"
            "        on\n"
            "        softness 12\n"
            "    }\n"
            "}\n"
            "window-rule {\n"
            "    geometry-corner-radius 12\n"
            "    clip-to-geometry true\n"
            "}\n"
            "animations {\n"
            "    slowdown 1.0\n"
            "}\n"
        )
        result = self.transaction().transact("user-appearance", candidate)
        self.assertEqual(result["status"], "success", result)
        target = self.config_root / "sparrow" / "user-appearance.kdl"
        self.assertEqual(target.read_text(encoding="utf-8"), candidate)
        self.assertEqual(self.reload_count, 1)
        self.validate_active_fixture()

        for slowdown in ("0.75", "1.0", "1.5"):
            variant = candidate.replace("slowdown 1.0", "slowdown " + slowdown)
            self.assertTrue(TRANSACTION.ConfigTransaction._safe_fragment_payload("user-appearance", variant))
        for gaps in (0, 1, 20, 40):
            variant = (candidate.replace("gaps 8", f"gaps {gaps}")
                       .replace("left 8", f"left {gaps}")
                       .replace("right 8", f"right {gaps}")
                       .replace("top -8", f"top {-gaps}")
                       .replace("bottom 8", f"bottom {gaps}"))
            self.assertTrue(TRANSACTION.ConfigTransaction._safe_fragment_payload("user-appearance", variant))
        for strut in ("left 8", "right 8", "bottom 8"):
            mismatched_strut = candidate.replace(strut, strut.split()[0] + " 12")
            self.assertFalse(TRANSACTION.ConfigTransaction._safe_fragment_payload("user-appearance", mismatched_strut))
        off_variant = candidate.replace("slowdown 1.0", "off")
        self.assertTrue(TRANSACTION.ConfigTransaction._safe_fragment_payload("user-appearance", off_variant))
        off_result = self.transaction().transact("user-appearance", off_variant)
        self.assertEqual(off_result["status"], "success", off_result)
        self.validate_active_fixture()

        unsafe = candidate + (
            "layer-rule {\n"
            '    match namespace="^pill$"\n'
            "    background-effect {\n"
            "        blur true\n"
            "    }\n"
            "}\n"
        )
        self.assertFalse(TRANSACTION.ConfigTransaction._safe_fragment_payload("user-appearance", unsafe))
        out_of_range = (candidate.replace("    gaps 8", "    gaps 80")
                        .replace("left 8", "left 80")
                        .replace("right 8", "right 80")
                        .replace("top -8", "top -80")
                        .replace("bottom 8", "bottom 80"))
        self.assertFalse(TRANSACTION.ConfigTransaction._safe_fragment_payload("user-appearance", out_of_range))
        extra_directive = candidate.replace("        left 8", "        left 0")
        self.assertFalse(TRANSACTION.ConfigTransaction._safe_fragment_payload("user-appearance", extra_directive))

    def test_user_input_fragment_accepts_managed_classes_and_rejects_injection(self):
        candidate = (
            "// Generated by Sparrow Input; do not edit.\n"
            "input {\n"
            "    keyboard {\n"
            '        xkb {\n            layout "si"\n        }\n'
            "        numlock\n        repeat-rate 25\n        repeat-delay 600\n"
            "    }\n"
            "    touchpad {\n        tap\n        natural-scroll\n        dwt\n"
            '        accel-speed -0.2\n        accel-profile "adaptive"\n'
            "    }\n"
            "    mouse {\n        natural-scroll\n        left-handed\n"
            '        accel-speed 0.1\n        accel-profile "flat"\n'
            "    }\n"
            "    touch {\n        map-to-output \"eDP-1\"\n    }\n"
            "    tablet {\n        map-to-focused-output\n    }\n"
            "    focus-follows-mouse\n"
            "}\n"
        )
        result = self.transaction().transact("user-input", candidate)
        self.assertEqual(result["status"], "success", result)
        self.assertEqual((self.config_root / "sparrow" / "user-input.kdl").read_text(encoding="utf-8"), candidate)
        self.validate_active_fixture()
        self.fail_next_reload = True
        changed = candidate.replace('layout "si"', 'layout "de"')
        result = self.transaction().transact("user-input", changed)
        self.assertEqual(result["status"], "reload_failed", result)
        self.assertTrue(result["rollbackSucceeded"], result)
        self.assertEqual((self.config_root / "sparrow" / "user-input.kdl").read_text(encoding="utf-8"), candidate)

        for invalid in (
            candidate + 'spawn "kitty"\n',
            candidate.replace('layout "si"', 'layout "../../tmp"'),
            candidate.replace('accel-speed -0.2', 'accel-speed 3'),
            candidate.replace('repeat-rate 25', 'repeat-rate 0'),
            candidate.replace('map-to-focused-output', 'map-to-focused-output\n        map-to-output "eDP-1"'),
            candidate.replace('        natural-scroll\n', '        tap\n        natural-scroll\n', 1),
            candidate.replace('focus-follows-mouse', 'focus-follows-mouse\n    layer-rule {\n'),
        ):
            self.assertFalse(TRANSACTION.ConfigTransaction._safe_fragment_payload("user-input", invalid), invalid)

